"""
Validation of the fraud model on the project's SYNTHETIC data, done properly.

    cd ml_service
    python3 generate_dataset.py                                   # data/transactions.csv
    python3 generate_dataset.py --seed 7 --shift_start_frac 0.624 \
            --out data/transactions_shift.csv                     # fraud pattern changes mid-timeline
    python3 -m evaluation.run_synthetic

Writes reports/evaluation/synthetic.json and synthetic.md.

EVERY number here comes from synthetic data. They show whether the modelling
pipeline is sound and how it degrades under controlled stress — they do NOT
establish real-world fraud-detection accuracy. See docs/MODEL_VALIDATION.md.
"""

import json
import os
import sys
import time

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from evaluation import metrics as M
from evaluation import segments as S
from evaluation.protocol import fit_select_calibrate, recommend_thresholds, score
from evaluation.splits import chronological_split, random_split, user_holdout
from utils.feature_engineering import engineer_features

DATA = "data/transactions.csv"
DATA_SHIFT = "data/transactions_shift.csv"
OUT_DIR = "reports/evaluation"
USER, TS = "user_synthetic_id", "timestamp"
REVIEW_THRESHOLD_FOR_SEGMENTS = 0.10   # calibrated P >= 10% -> send to review (reference point)
CAPACITY = 0.02

DISCLAIMER = ("SYNTHETIC-DATA RESULTS. Generated by ml_service/generate_dataset.py. These numbers validate the "
              "modelling pipeline under controlled conditions; they do NOT measure real-world fraud-detection accuracy.")


def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def load(path):
    df = pd.read_csv(path)
    df = S.add_context(df, USER, TS)
    X = engineer_features(df)
    return df, X, df["is_fraud"].to_numpy()


def headline(df, y, idx, raw, cal):
    """Metric block for a set of test rows (index labels `idx`)."""
    pos = df.index.get_indexer(idx)
    return {"raw_model_output": M.summary(y[pos], raw), "calibrated": M.summary(y[pos], cal)}


def run_experiment(df, X, y, train, val, test, label, split_info, extra_test=None):
    log(f"{label}: fitting on {len(train):,} rows (val {len(val):,}, test {len(test):,})")
    fit = fit_select_calibrate(X, y, train, val)
    log(f"{label}: best model on VALIDATION = {fit['best']} {fit['val_pr_auc']}")
    raw, cal = score(fit, X.loc[test])
    block = {
        "split": split_info,
        "model_selected_on_validation": fit["best"],
        "validation_pr_auc_by_model": fit["val_pr_auc"],
        "calibrator": fit["calibrator"].describe(),
        "test": headline(df, y, test, raw, cal),
        "recommended_thresholds_from_validation": recommend_thresholds(fit["val_y"], fit["val_calibrated"], CAPACITY),
    }
    return fit, raw, cal, block


def main():
    t_all = time.time()
    df, X, y = load(DATA)
    report = {"dataset": "synthetic", "disclaimer": DISCLAIMER, "data_file": DATA,
              "n_rows": int(len(df)), "n_users": int(df[USER].nunique()), "fraud_rate": round(float(y.mean()), 5),
              "experiments": {}}

    # ---- A. naive random split (shows how much it inflates) ----
    tr, va, te, info = random_split(df)
    _, _, _, a = run_experiment(df, X, y, tr, va, te, "A random split", info)
    report["experiments"]["A_random_split_naive_baseline"] = a

    # ---- B. chronological, purged ----
    tr, va, te, info = chronological_split(df, TS, user_col=USER)
    fitB, rawB, calB, b = run_experiment(df, X, y, tr, va, te, "B chronological", info)
    report["experiments"]["B_chronological_purged"] = b

    # Segments on the chronological test set
    test_df = df.loc[te]
    yt = y[df.index.get_indexer(te)]
    b["segments_feature_defined"] = S.evaluate_feature_segments(test_df, yt, calB, REVIEW_THRESHOLD_FOR_SEGMENTS, CAPACITY)
    b["segments_fraud_type"] = S.evaluate_fraud_type_segments(test_df, yt, calB, REVIEW_THRESHOLD_FOR_SEGMENTS)
    b["segment_review_threshold_used"] = REVIEW_THRESHOLD_FOR_SEGMENTS

    # ---- B2. hard rules evaluated SEPARATELY from the model ----
    rule = ((test_df["location"] == "Anonymous Proxy") | (test_df["amount"] > 10000)).to_numpy()
    ml_flag = calB >= REVIEW_THRESHOLD_FOR_SEGMENTS
    def pr(flag):
        tp = int((flag & (yt == 1)).sum()); fp = int((flag & (yt == 0)).sum())
        return {"flagged": tp + fp, "precision": round(tp / (tp + fp), 4) if tp + fp else None,
                "recall": round(tp / yt.sum(), 4), "false_positives": fp}
    b["hard_rules_vs_model"] = {
        "note": ("Rules mirrored from the backend defaults that the dataset can express: location == 'Anonymous Proxy' "
                 "or amount > $10,000. In this generator 'Anonymous Proxy' is only ever chosen for fraud, so the rule is "
                 "perfectly precise BY CONSTRUCTION — that says nothing about real-world rule precision. Measure that from "
                 "reviewed alerts in production (GET /admin/risk-policy/calibration)."),
        "hard_rules_only": pr(rule), "model_only": pr(ml_flag), "model_or_rules": pr(ml_flag | rule),
        "fraud_caught_only_by_rules": int((rule & ~ml_flag & (yt == 1)).sum()),
        "fraud_caught_only_by_model": int((ml_flag & ~rule & (yt == 1)).sum()),
    }

    # ---- C. brand-new customers: users entirely unseen in training/calibration ----
    held = user_holdout(df, USER, 0.2)
    tr0, va0, te0, info0 = chronological_split(df, TS, user_col=USER)
    is_held = lambda idx: df.loc[idx, USER].isin(held).to_numpy()
    trC, vaC = tr0[~is_held(tr0)], va0[~is_held(va0)]
    teKnown, teNew = te0[~is_held(te0)], te0[is_held(te0)]
    info0 = {**info0, "split": "chronological + 20% of users held out entirely",
             "held_out_users": len(held),
             "rows": {"train": len(trC), "validation": len(vaC), "test_known_users": len(teKnown), "test_unseen_users": len(teNew)}}
    fitC, _, _, c = run_experiment(df, X, y, trC, vaC, teKnown, "C user-disjoint", info0)
    c["test_unseen_users"] = headline(df, y, teNew, *score(fitC, X.loc[teNew]))
    c["test_known_users_in_future"] = c.pop("test")
    # Cold start: the FIRST 3 transactions of customers the model has never seen. A chronological test
    # window cannot contain these (every customer already has history by then), so they are taken from
    # the held-out users' whole timeline. Their own rows were never used for fitting or calibration;
    # the only reuse is calendar overlap with other users' training data.
    held_rows = df[df[USER].isin(held) & (df["user_txn_index"] < 3)].index
    c["new_customer_first_3_txns_unseen_users"] = headline(df, y, held_rows, *score(fitC, X.loc[held_rows]))
    c["new_customer_note"] = ("First 3 transactions of unseen customers: there is no behavioural history, so velocity/z-score/"
                              "distance features take their cold-start defaults. Few fraud cases -> wide confidence interval.")
    report["experiments"]["C_chronological_plus_unseen_users"] = c

    # ---- D. fraud pattern changes ----
    if os.path.exists(DATA_SHIFT):
        dfS, XS, yS = load(DATA_SHIFT)
        trS, vaS, teS, infoS = chronological_split(dfS, TS, user_col=USER)
        for name, idx in (("train", trS), ("validation", vaS), ("test", teS)):
            infoS.setdefault("fraud_pattern_counts", {})[name] = dfS.loc[idx].query("is_fraud == 1")["fraud_pattern"].value_counts().to_dict()
        fitS, rawS, calS, d = run_experiment(dfS, XS, yS, trS, vaS, teS, "D pattern shift", infoS)
        ytS = yS[dfS.index.get_indexer(teS)]
        d["segments_fraud_type"] = S.evaluate_fraud_type_segments(dfS.loc[teS], ytS, calS, REVIEW_THRESHOLD_FOR_SEGMENTS)
        d["interpretation"] = ("Model trained and calibrated on the OLD fraud pattern, tested on a period where fraud has become "
                               "'low-and-slow'. Compare recall/PR-AUC with experiment B to see the cost of attackers adapting.")
        report["experiments"]["D_fraud_pattern_shift"] = d
    else:
        report["experiments"]["D_fraud_pattern_shift"] = {"skipped": f"{DATA_SHIFT} not found — see module docstring"}

    report["runtime_seconds"] = round(time.time() - t_all, 1)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "synthetic.json"), "w") as f:
        json.dump(report, f, indent=2, default=float)
    from evaluation.report import render_markdown
    with open(os.path.join(OUT_DIR, "synthetic.md"), "w") as f:
        f.write(render_markdown(report))
    log(f"done in {report['runtime_seconds']}s -> {OUT_DIR}/synthetic.(json|md)")


if __name__ == "__main__":
    main()
